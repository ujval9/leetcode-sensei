#!/usr/bin/env python3
"""Scan the repo and rebuild the progress files.

Usage:
    python3 tools/progress.py            # rewrite progress/TIP102.md and TIP102/README.md
    python3 tools/progress.py --summary  # same, then print a short summary (used by the SessionStart hook)

Status of each problem comes from the "# STATUS:" line at the top of its file.
If the line still says "not started" but you have written code or filled in UMPIRE,
the problem is counted as "in progress" automatically.
"""
import ast
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COURSE = os.path.join(ROOT, "TIP102")

WEEK_TOPICS = {
    1: "Strings & Arrays, UPI / UMPIRE",
    2: "Dictionaries (hash maps) and sets",
    3: "Stacks, queues, two pointers",
    4: "Review: hash maps, stacks, queues",
    5: "Classes (OOP) and intro to linked lists",
    6: "Linked lists: fast/slow pointers, cycles",
    7: "Recursion; binary search, divide and conquer",
    8: "Binary trees and binary search trees",
    9: "Tree traversals: BFS and DFS",
    10: "Graphs: representations, BFS, DFS",
    11: "Grids as graphs: BFS, DFS, connected components",
    12: "Dynamic programming and mixed review",
}

UMPIRE_EMPTY = re.compile(r'"""\nUNDERSTAND:\n    \* Input:\n    \* Output:\n')


def problem_status(path):
    src = open(path, encoding="utf-8").read()
    m = re.search(r"^# STATUS:\s*([a-z ]+?)\s*(\(|$)", src, re.M)
    status = m.group(1).strip() if m else "not started"
    if status == "not started":
        touched = not UMPIRE_EMPTY.search(src)
        try:
            for node in ast.walk(ast.parse(src)):
                if isinstance(node, ast.FunctionDef) and node.name not in ("__init__", "build_tree", "print_tree", "print_linked_list", "print_list"):
                    body = [b for b in node.body if not (isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant))]
                    if not (len(body) == 1 and isinstance(body[0], ast.Pass)):
                        touched = True
        except SyntaxError:
            touched = True
        if touched:
            status = "in progress"
    return status


def collect():
    rows = []
    for dirpath, _, files in os.walk(COURSE):
        for f in files:
            if not f.endswith(".py"):
                continue
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, ROOT)
            m = re.search(r"Week_(\d+)/Session_(\d)/Problem_Set_Version_(\d)/(\d+)_(.+)\.py$", rel.replace(os.sep, "/"))
            if not m:
                continue
            w, s, v, n, name = m.groups()
            rows.append(dict(week=int(w), session=int(s), version=int(v), num=int(n),
                             name=name.replace("_", " "), path=rel.replace(os.sep, "/"),
                             status=problem_status(p), mtime=os.path.getmtime(p)))
    rows.sort(key=lambda r: (r["week"], r["session"], r["version"], r["num"]))
    return rows


MARK = {"solved": "x", "solved with help": "x", "in progress": "~", "not started": " "}


def write_files(rows):
    done = [r for r in rows if r["status"].startswith("solved")]
    lines = ["# TIP102 Progress", "",
             "Generated by `python3 tools/progress.py`. Do not edit by hand; change the `# STATUS:` line in each problem file instead.", "",
             f"**Solved:** {len(done)} / {len(rows)}  |  **In progress:** {sum(r['status'] == 'in progress' for r in rows)}", "",
             "| Week | Topic | Session 1 (V1 / V2) | Session 2 (V1 / V2) |", "|---|---|---|---|"]
    for w in range(1, 13):
        cells = []
        for s in (1, 2):
            parts = []
            for v in (1, 2):
                grp = [r for r in rows if (r["week"], r["session"], r["version"]) == (w, s, v)]
                parts.append(f"{sum(r['status'].startswith('solved') for r in grp)}/{len(grp)}")
            cells.append(" / ".join(parts))
        lines.append(f"| {w} | {WEEK_TOPICS[w]} | {cells[0]} | {cells[1]} |")
    os.makedirs(os.path.join(ROOT, "progress"), exist_ok=True)
    open(os.path.join(ROOT, "progress", "TIP102.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

    idx = ["# TIP102 Problems", "",
           "12 weeks x 2 sessions x 2 problem set versions. `[x]` solved, `[~]` in progress, `[ ]` not started.",
           "Start with Version 1 of each session; Version 2 covers the same ideas with different problems, so use it for extra reps.",
           "Refresh with `python3 tools/progress.py` (runs automatically when Claude Code starts).", ""]
    for w in range(1, 13):
        idx += [f"## Week {w}: {WEEK_TOPICS[w]}", ""]
        for s in (1, 2):
            for v in (1, 2):
                grp = [r for r in rows if (r["week"], r["session"], r["version"]) == (w, s, v)]
                if not grp:
                    continue
                idx.append(f"**Session {s}, Problem Set Version {v}**")
                idx.append("")
                for r in grp:
                    rel = r["path"].split("TIP102/", 1)[1]
                    idx.append(f"- [{MARK.get(r['status'], ' ')}] {r['num']}. [{r['name']}]({rel})")
                idx.append("")
    open(os.path.join(COURSE, "README.md"), "w", encoding="utf-8").write("\n".join(idx))
    return done


def summary(rows, done):
    print(f"TIP102 progress: {len(done)}/{len(rows)} solved, "
          f"{sum(r['status'] == 'in progress' for r in rows)} in progress.")
    inprog = sorted([r for r in rows if r["status"] == "in progress"], key=lambda r: -r["mtime"])[:3]
    for r in inprog:
        print(f"  In progress: {r['path']}")
    nxt = next((r for r in rows if r["status"] == "not started"), None)
    if nxt:
        print(f"  Next unstarted: Week {nxt['week']} Session {nxt['session']} V{nxt['version']} #{nxt['num']} {nxt['name']} ({nxt['path']})")
    weak = os.path.join(ROOT, "progress", "weak-patterns.md")
    if os.path.exists(weak):
        wl = [l for l in open(weak, encoding="utf-8").read().splitlines() if l.startswith("|") and "---" not in l][1:]
        if wl:
            print("  Weak patterns:")
            for l in wl[:5]:
                print("   " + l)
    log = os.path.join(ROOT, "progress", "log.md")
    if os.path.exists(log):
        ll = [l for l in open(log, encoding="utf-8").read().splitlines() if l.startswith("| 20")]
        if ll:
            print("  Last logged attempts:")
            for l in ll[-3:]:
                print("   " + l)
    try:
        git = subprocess.run(["git", "-C", ROOT, "log", "-1", "--format=%cr: %s"], capture_output=True, text=True, timeout=5)
        if git.stdout.strip():
            print(f"  Last commit {git.stdout.strip()}")
    except Exception:
        pass


if __name__ == "__main__":
    rows = collect()
    done = write_files(rows)
    if "--summary" in sys.argv:
        summary(rows, done)
